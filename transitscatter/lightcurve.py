"""Synthetic transit light-curve generator.

Produces injection-recovery test cases: a flat/red-noise stellar baseline with
an injected periodic trapezoidal transit signal, at controllable SNR.
No external data required — everything is simulated so the benchmark is
fully reproducible from a random seed.
"""
from __future__ import annotations

import numpy as np
from dataclasses import dataclass


@dataclass
class TransitParams:
    period_days: float
    depth_ppm: float
    duration_hours: float
    epoch_days: float


def trapezoidal_transit(time: np.ndarray, params: TransitParams) -> np.ndarray:
    """Return a fractional-flux trapezoidal transit model sampled at `time`."""
    depth = params.depth_ppm * 1e-6
    dur = params.duration_hours / 24.0
    ingress = 0.2 * dur  # ingress/egress each take 20% of total duration

    phase = ((time - params.epoch_days + 0.5 * params.period_days) % params.period_days) - 0.5 * params.period_days
    half_flat = 0.5 * dur - ingress
    abs_phase = np.abs(phase)

    flux = np.zeros_like(time)
    flat = abs_phase <= half_flat
    slope = (abs_phase > half_flat) & (abs_phase <= half_flat + ingress)

    flux[flat] = -depth
    frac = (half_flat + ingress - abs_phase[slope]) / ingress
    flux[slope] = -depth * frac
    return flux


def simulate_light_curve(
    n_points: int = 4000,
    baseline_days: float = 27.0,
    period_days: float = 3.2,
    depth_ppm: float = 500.0,
    duration_hours: float = 3.0,
    epoch_days: float | None = None,
    white_noise_ppm: float = 200.0,
    red_noise_amp_ppm: float = 80.0,
    red_noise_tau_days: float = 0.6,
    flare_rate_per_day: float = 0.0,
    flare_amp_ppm_range: tuple = (1500.0, 6000.0),
    flare_decay_hours: float = 2.0,
    rng: np.random.Generator | None = None,
):
    """Simulate a noisy light curve with an injected periodic transit.

    Returns (time, flux, params, snr_estimate).
    Noise model: white Gaussian noise + a smooth red-noise component
    (Ornstein-Uhlenbeck-like, generated by low-pass filtering white noise)
    to mimic stellar granulation / systematics, which is what makes
    low-SNR transit detection genuinely hard.
    """
    rng = rng or np.random.default_rng()
    time = np.linspace(0, baseline_days, n_points)
    if epoch_days is None:
        epoch_days = rng.uniform(0, period_days)

    params = TransitParams(period_days, depth_ppm, duration_hours, epoch_days)
    transit_signal = trapezoidal_transit(time, params)

    white = rng.normal(0, white_noise_ppm * 1e-6, n_points)

    # Red noise via exponential-kernel smoothing of white noise (fast O(n) recursion).
    dt = time[1] - time[0]
    alpha = dt / red_noise_tau_days
    raw = rng.normal(0, red_noise_amp_ppm * 1e-6, n_points)
    red = np.zeros(n_points)
    red[0] = raw[0]
    for i in range(1, n_points):
        red[i] = red[i - 1] + alpha * (raw[i] - red[i - 1])

    flux = 1.0 + transit_signal + white + red

    # optionally inject stellar-flare-like outliers: fast rise, exponential decay
    n_flares = rng.poisson(flare_rate_per_day * baseline_days)
    for _ in range(n_flares):
        t_flare = rng.uniform(0, baseline_days)
        amp = rng.uniform(*flare_amp_ppm_range) * 1e-6
        tau = flare_decay_hours / 24.0
        dt_from_flare = time - t_flare
        shape = np.where(dt_from_flare >= 0, np.exp(-dt_from_flare / tau), 0.0)
        flux += amp * shape

    total_noise_ppm = np.sqrt(white_noise_ppm ** 2 + red_noise_amp_ppm ** 2)
    n_in_transit = int(np.sum(np.abs(((time - epoch_days + 0.5 * period_days) % period_days) - 0.5 * period_days) <= duration_hours / 48.0))
    snr_estimate = (depth_ppm / total_noise_ppm) * np.sqrt(max(n_in_transit, 1))

    return time, flux, params, snr_estimate
